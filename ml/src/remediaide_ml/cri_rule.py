"""
B0 baseline: exact Python port of the RemediAide v1 rule-based CRI engine.

Source of truth (TypeScript, do NOT diverge):
  src/lib/diagnostic/engine.ts      -> countWords, calculateTauMin, calculateIntegrityIndex,
                                       classifyPerItem, aggregateMajorityVoting
  src/lib/diagnosis/compute.ts      -> computeDominantStatus, tauMinMs = tauMinSeconds * 1000

Parity with the TypeScript implementation is enforced by tests/test_cri_rule.py using
tests/fixtures/ts_parity_cases.json, which was generated by running engine.ts itself.

Notes on v1 behaviour that the CAC report must state explicitly (see docs/cac/DECISIONS.md D-03):
  * The code uses an integer CRI threshold `cri >= 3`. The LIDM proposal text says `CRI >= 2.5`.
    For integer CRI 0..5 both are identical. For Eedi confidence mapped as conf/20 (continuous)
    `>= 2.5` <=> conf >= 50, and the half-up integer mapping `cri_int >= 3` <=> conf >= 50 too.
  * Any response faster than tau_min is INVALID in code, even if it is correct. The proposal text
    describes an asymmetric penalty that only applies to wrong answers. The code is B0.
"""

from __future__ import annotations

import math
import re
from collections.abc import Iterable
from dataclasses import dataclass, field
from typing import Literal

CognitiveStatus = Literal[
    "PAHAM_KONSEP", "LUCKY_GUESS", "MISKONSEPSI", "TIDAK_PAHAM", "INVALID", "INSUFFICIENT_DATA"
]

ALL_STATUSES: tuple[str, ...] = (
    "PAHAM_KONSEP", "LUCKY_GUESS", "MISKONSEPSI", "TIDAK_PAHAM", "INVALID", "INSUFFICIENT_DATA",
)

# Tie-break precedence, highest priority first (engine.ts PRECEDENCY).
PRECEDENCY: tuple[str, ...] = ("MISKONSEPSI", "LUCKY_GUESS", "TIDAK_PAHAM", "PAHAM_KONSEP")

READING_SPEED_WPS = 2.5  # words per second (engine.ts READING_SPEED_WPS)
CRI_HIGH_THRESHOLD = 3   # integer threshold used by engine.ts (cri >= 3 is "high")

_NON_WORD = re.compile(r"[^A-Za-z0-9_\s]")  # JS /[^\w\s]/ : JS \w is ASCII-only
_WS = re.compile(r"\s+")


def count_words(text: str | None) -> int:
    """Port of countWords(): lowercase, strip punctuation, collapse whitespace, split."""
    if not text or text.strip() == "":
        return 0
    normalised = _WS.sub(" ", _NON_WORD.sub(" ", text.lower())).strip()
    if normalised == "":
        return 0
    return len([w for w in normalised.split(" ") if len(w) > 0])


def calculate_tau_min_seconds(word_count: int) -> int:
    """Port of calculateTauMin(): ceil(L / 2.5) seconds, minimum 1 second."""
    if word_count <= 0:
        return 1
    return math.ceil(word_count / READING_SPEED_WPS)


def tau_min_ms_for_text(text: str | None) -> int:
    """compute.ts uses variant.tauMinSeconds * 1000."""
    return calculate_tau_min_seconds(count_words(text)) * 1000


@dataclass(frozen=True)
class ResponseInput:
    item_id: str
    is_correct: bool
    cri_value: int            # integer 0..5
    response_time_ms: float
    tau_min_ms: float


@dataclass(frozen=True)
class DiagnosisResult:
    item_id: str
    status: str
    integrity_index: float
    is_below_threshold: bool


def calculate_integrity_index(inp: ResponseInput) -> float:
    """Port of calculateIntegrityIndex()."""
    if inp.response_time_ms < inp.tau_min_ms:
        return 0.0
    if inp.is_correct and inp.cri_value >= CRI_HIGH_THRESHOLD:
        return 1.0
    if inp.is_correct and inp.cri_value < CRI_HIGH_THRESHOLD:
        return 0.6 + (inp.cri_value / 5) * 0.4
    if (not inp.is_correct) and inp.cri_value >= CRI_HIGH_THRESHOLD:
        return 0.0
    return 0.3 + (inp.cri_value / 5) * 0.3


def classify_per_item(inp: ResponseInput) -> DiagnosisResult:
    """Port of classifyPerItem()."""
    below = inp.response_time_ms < inp.tau_min_ms
    ii = calculate_integrity_index(inp)
    if below or ii == 0.0:
        if below:
            status = "INVALID"
        elif (not inp.is_correct) and inp.cri_value >= CRI_HIGH_THRESHOLD:
            status = "MISKONSEPSI"
        else:
            status = "INVALID"
    else:
        if inp.is_correct and inp.cri_value >= CRI_HIGH_THRESHOLD:
            status = "PAHAM_KONSEP"
        elif inp.is_correct and inp.cri_value < CRI_HIGH_THRESHOLD:
            status = "LUCKY_GUESS"
        else:
            status = "TIDAK_PAHAM"
    return DiagnosisResult(inp.item_id, status, ii, below)


def classify_quadrant(is_correct: bool, cri_value: int) -> str:
    """Quadrant only (no time filter). Used on datasets without response time (Eedi 2020)."""
    high = cri_value >= CRI_HIGH_THRESHOLD
    if is_correct:
        return "PAHAM_KONSEP" if high else "LUCKY_GUESS"
    return "MISKONSEPSI" if high else "TIDAK_PAHAM"


@dataclass
class AggregationResult:
    final_status: str
    voting_tally: dict[str, int] = field(default_factory=dict)
    tiebreaker_applied: bool = False
    valid_item_count: int = 0


def aggregate_majority_voting(results: Iterable[DiagnosisResult]) -> AggregationResult:
    """Port of aggregateMajorityVoting() (per student x question, across variants)."""
    results = list(results)
    tally = {s: 0 for s in ALL_STATUSES}
    for r in results:
        tally[r.status] += 1
    valid = [r for r in results if r.status != "INVALID"]
    n = len(valid)
    if n < 1:
        return AggregationResult("INSUFFICIENT_DATA", tally, False, n)
    if n == 1:
        return AggregationResult(valid[0].status, tally, False, 1)
    vt: dict[str, int] = {}
    for r in valid:
        vt[r.status] = vt.get(r.status, 0) + 1
    mx = max(vt.values())
    cands = [s for s, f in vt.items() if f == mx]
    if len(cands) == 1:
        return AggregationResult(cands[0], tally, False, n)
    winner = next(s for s in PRECEDENCY if s in cands)
    return AggregationResult(winner, tally, True, n)


def final_status_from_aggregation(agg: AggregationResult) -> str:
    """compute.ts maps INVALID -> INSUFFICIENT_DATA for the stored finalStatus."""
    return "INSUFFICIENT_DATA" if agg.final_status == "INVALID" else agg.final_status


def compute_dominant_status(statuses: Iterable[str]) -> str:
    """Port of computeDominantStatus() (per student, across questions)."""
    statuses = list(statuses)
    if not statuses:
        return "INSUFFICIENT_DATA"
    tally: dict[str, int] = {}
    for s in statuses:
        tally[s] = tally.get(s, 0) + 1
    mx = max(tally.values())
    cands = [s for s, f in tally.items() if f == mx]
    if len(cands) == 1:
        return cands[0]
    for s in PRECEDENCY:
        if s in cands:
            return s
    return "INSUFFICIENT_DATA"


def confidence_to_cri(confidence: float | None) -> int | None:
    """Eedi Confidence 0..100 -> integer CRI 0..5, half-up (0-9->0, 10-29->1, ..., 90-100->5).

    Chosen so that cri >= 3  <=>  confidence >= 50, which equals the proposal's continuous
    rule conf/20 >= 2.5. Returns None for missing confidence.
    """
    if confidence is None or (isinstance(confidence, float) and math.isnan(confidence)):
        return None
    c = max(0.0, min(100.0, float(confidence)))
    return int(min(5, math.floor((c + 10) / 20)))


